"""Render complete comparison tables from frozen, attributed source snapshots."""
import csv
import hashlib
import json
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(name):
    return json.loads((HERE / name).read_text())


def tex(value):
    replacements = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$"}
    return "".join(replacements.get(c, c) for c in str(value))


def displayed(value):
    return Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def rank(score, peers):
    return 1 + sum(displayed(p) > displayed(score) for p in peers)


def row(values, highlight=False):
    prefix = r"\rowcolor{teal!9} " if highlight else ""
    cells = [tex(v) for v in values]
    if highlight:
        cells = [r"\textbf{" + v + "}" for v in cells]
    return prefix + " & ".join(cells) + r"\\" + "\n"


def main():
    provenance = load("provenance.json")
    for name, expected_hash in provenance["snapshot_sha256"].items():
        assert hashlib.sha256((HERE / name).read_bytes()).hexdigest() == expected_hash, name
    published = load("unikie-published.json")
    unikie = load("docquorum-unikie.json")
    eb = load("docquorum-extractbench.json")
    with (HERE / "extractbench-leaderboard.csv").open(newline="") as handle:
        eb_rows = list(csv.DictReader(handle))
    # Match the upstream headline table's order, including its cost tie-break.
    eb_rows.sort(key=lambda x: (-Decimal(x["Overall"]), Decimal(x["Cost_Per_Page"] or "Infinity")))
    u_rows = [(name, values, "Closed") for name, values in published["closed_source"].items()]
    u_rows += [(name, values, "Open") for name, values in published["open_source"].items()]
    u_rows.sort(key=lambda x: -x[1][-1])
    assert len(eb_rows) == provenance["extractbench"]["published_systems"] == 49
    assert len(u_rows) == provenance["unikie"]["published_systems"] == 15
    eb_peers = [x["Overall"] for x in eb_rows]
    u_peers = [values[-1] for _, values, _ in u_rows]
    original = unikie["variants"]["three_original_readings"]
    four = unikie["variants"]["four_readings"]
    six = unikie["variants"]["six_readings"]
    primary = eb["stored_primary"]
    repair = eb["incremental_development"]
    assert rank(primary["score"], eb_peers) == rank(repair["score"], eb_peers) == 5
    assert rank(original["score"], u_peers) == rank(four["score"], u_peers) == 2
    assert rank(six["score"], u_peers) == 1
    assert displayed(six["score"]) == displayed(u_peers[0])
    date = provenance["display_date"]
    eb_url = provenance["extractbench"]["url"]
    u_url = provenance["unikie"]["url"]
    out = [r"% Generated by results/generate_tables.py; edit the snapshots or generator." + "\n"]
    out.append(r"""
\chapterpage{RESULTS / COMPLETE COMPARISON TABLES}{DocQuorum's measured standing}\label{sec:results}
""")
    out.append(f"Published comparison snapshots checked {date}. The following pages include every published system in UNIKIE Table 4 and ExtractBench's value-F1 leaderboard, with DocQuorum rows highlighted.\n\n")
    out.append(r"""
\sub{Rank and score at a glance}
\begin{tabularx}{\linewidth}{@{}Yrrp{26mm}@{}}\toprule
Benchmark / DocQuorum configuration & F1 (\%) & Ref. rank & Coverage\\\midrule
""")
    for benchmark, value, ref, coverage in [
        ("ExtractBench / stored primary", primary["score"], "5", "370 / 370"),
        ("ExtractBench / incremental development", repair["score"], "5", "370 / 370"),
        ("UNIKIE / original 3 readings", original["score"], "2", "4,472 / 4,472"),
        ("UNIKIE / development 4 readings", four["score"], "2", "4,472 / 4,472"),
        ("UNIKIE / tuned 6 readings", six["score"], "1 (tie)", "4,472 / 4,472"),
    ]:
        out.append(row([benchmark, f"{value:.4f}", ref, coverage], True))
    out.append(r"\bottomrule\end{tabularx}" + "\n\n")
    out.append(r"""
\textbf{Reference rank} compares each DocQuorum configuration independently against the published systems at their displayed two-decimal precision. Local variants do not compete with one another. These are comparison positions; no external leaderboard submission has been accepted.

\sub{How far are we from the leaders?}
""")
    out.append(f"ExtractBench's current leader scores {eb_rows[0]['Overall']}. The stored primary result is {float(eb_rows[0]['Overall']) - primary['score']:.4f} percentage points below it and {float(eb_rows[2]['Overall']) - primary['score']:.4f} below the third-place score of {eb_rows[2]['Overall']}. The incremental development result narrows these gaps to {float(eb_rows[0]['Overall']) - repair['score']:.4f} and {float(eb_rows[2]['Overall']) - repair['score']:.4f}. Both configurations now have reference rank 5; the older rank-3 comparison used an earlier leaderboard snapshot.\n\n")
    out.append(f"On UNIKIE, the original configuration is {float(u_peers[0]) - original['score']:.4f} points below the leader and {original['score'] - float(u_peers[2]):.4f} above the published third-place score. The tuned configuration rounds to 82.37, matching Gemini-3-Pro. Its displayed first-place tie does not establish a statistically significant advantage.\n\n")
    out.append(r"""
\sub{What the measurements cover}
\textbf{ExtractBench:} 370 enterprise PDFs; overall unified value F1 is the unweighted mean over documents. The stored-primary row reuses the archived evaluation after prediction-hash validation. The incremental repair row is development work using stored primary outputs and fixed verifier readings, with 14 improved documents and no regressions. Neither row is fresh full inference or a held-out result.

\textbf{UNIKIE:} 4,472 documents in the constrained-category track; macro field F1 is the mean of 11 scenario scores. The three-reading row preserves the original configuration. Four and six readings were added during development; their scores must remain separate from that original result. All rows are full stored-output re-scores. The multi-category track was not evaluated here.

\sub{Sources and reproducibility}
""")
    out.append(f"Published baselines: \\href{{{u_url}}}{{UNIKIE-BENCH, Table 4}} and \\href{{{eb_url}}}{{ExtractBench, pinned full CSV}}. The ExtractBench dataset revision still matches our recorded evaluation, and all 95 evaluation-source files are unchanged between the recorded scorer revision and this snapshot.\n\n")
    out.append(r"{\small Local measurements: \code{results/multibench/unikie_audit.json}, \code{extractbench_current_reference.json}, and \code{extractbench_archived_candidate.json}. Frozen tables, source hashes, and a deterministic table generator are in \code{docs/results/}. No new inference was run for this section.}" + "\n")

    out.append(r"""
\begin{landscape}
\chapterpage{RESULTS / UNIKIE\hfill\textcolor{ink!70}{DOCQUORUM / \thepage}}{All 11 scenarios and all 15 published systems}\label{results:unikie}
\thispagestyle{empty}
Constrained-category track, 4,472 documents. Field F1 (\%); Avg. is the macro mean over scenarios. ``Pub.'' is the published-system rank by average; local ranks appear below.

\begingroup\fontsize{8.5}{11}\selectfont
\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.12}
\begin{tabularx}{\linewidth}{@{}rYl*{12}{r}@{}}\toprule
Pub. & System / configuration & Type & Ret. & Cat. & Com. & Acco. & Post. & Admi. & Edu. & Adv. & Tax. & Med. & Nut. & Avg.\\\midrule
""")
    for i, (name, values, kind) in enumerate(u_rows, 1):
        out.append(row([i, name, kind] + [f"{v:.2f}" for v in values]))
    out.append(r"\midrule" + "\n")
    scenario_columns = published["columns"][:-1]
    for name, key in [("DocQuorum / original 3 readings", "three_original_readings"), ("DocQuorum / development 4 readings", "four_readings"), ("DocQuorum / tuned 6 readings", "six_readings")]:
        variant = unikie["variants"][key]
        out.append(row(["--", name, "Local"] + [f"{variant['per_scenario'][c]:.2f}" for c in scenario_columns] + [f"{variant['score']:.2f}"], True))
    out.append(r"""
\bottomrule\end{tabularx}\endgroup

\textbf{DocQuorum reference ranks:} original 3 readings: \textbf{2}; development 4 readings: \textbf{2}; tuned 6 readings: \textbf{1, displayed tie} with Gemini-3-Pro. Compare each local variant separately against the 15 published rows; no accepted external submission.

{\small\textbf{Column key:} Ret. = Retail; Cat. = Catering-Services; Com. = Commercial; Acco. = Accommodation; Post. = Postal-Label; Admi. = Administrative; Edu. = Education; Adv. = Advertisement; Tax. = Tax-Compliant; Med. = Medical-Services; Nut. = Nutrition-Label. Closed/Open label the published model groups; Local denotes our pipeline.}

""")
    out.append(f"{{\\small\\color{{ink!75}}Published values: \\href{{{u_url}}}{{UNIKIE-BENCH Table 4, arXiv v2}}; all 15 rows and 12 numerical columns verified {date}. DocQuorum: full stored-output re-scores; six readings is a tuned development configuration. Scenario values are rounded individually, so the displayed average can differ from the mean of displayed cells.}}\n")
    out.append(r"\end{landscape}" + "\n")

    for part, peers in enumerate([eb_rows[:25], eb_rows[25:]], 1):
        start = 1 if part == 1 else 26
        end = 25 if part == 1 else 49
        label = r"\label{results:extractbench}" if part == 1 else ""
        out.append(r"\begin{landscape}" + "\n")
        out.append(r"\chapterpage{RESULTS / EXTRACTBENCH " + str(part) + r" OF 2\hfill\textcolor{ink!70}{DOCQUORUM / \thepage}}{Complete value-F1 table: published ranks " + f"{start}--{end}" + "}" + label + "\n")
        out.append(r"\thispagestyle{empty}" + "\n")
        out.append(f"All 49 published systems are included across these two pages. Snapshot: {date}; 370 PDFs. Higher F1 is better. ``Pub.'' retains the source order; each local reference rank is computed separately.\n\n")
        out.append(r"""
\begingroup\fontsize{9}{10.5}\selectfont
\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.06}
\begin{tabularx}{\linewidth}{@{}rYp{33mm}rrrrr@{}}\toprule
Pub. / ref. & Provider / configuration & Category & Overall & Short & Medium & Long & cents/page\\\midrule
""")
        if part == 1:
            splits = primary["per_split"]
            out.append(row(["5 ref.", "DocQuorum / stored primary", "Local stored-output", f"{primary['score']:.2f}", f"{splits['short']:.2f}", f"{splits['medium']:.2f}", f"{splits['long']:.2f}", "n/r"], True))
            out.append(row(["5 ref.", "DocQuorum / incremental repair", "Local development", f"{repair['score']:.2f}", "n/r", "n/r", "n/r", "n/r"], True))
            out.append(r"\midrule" + "\n")
        for index, peer in enumerate(peers, start):
            cost = f"{Decimal(peer['Cost_Per_Page']) * 100:.2f}" if peer["Cost_Per_Page"] else "n/r"
            out.append(row([index, peer["Provider"], peer["Category"], peer["Overall"], peer["Short"], peer["Medium"], peer["Long"], cost]))
        out.append(r"\bottomrule\end{tabularx}\endgroup" + "\n\n")
        if part == 1:
            out.append(r"{\small \textbf{Local rows:} recorded complete-cohort evaluations, not fresh inference. Incremental repair uses stored outputs and verifier readings; its split breakdown is not reported in the source summary. n/r = not reported; no local cost claim. Published ranks continue on the next page.}" + "\n\n")
        else:
            out.append(r"{\small \textbf{Metric:} Overall, Short, Medium and Long are mean document unified value F1 (\%). Overall weights every document equally: 252 short, 98 medium and 20 long; it is not the mean of the three split columns. OSS = open-source/self-hosted systems. Cost is the published dollar-per-page value converted to cents; n/r = not reported.}" + "\n\n")
        out.append(f"{{\\footnotesize\\color{{ink!75}}Source: \\href{{{eb_url}}}{{ExtractBench leaderboard.csv}}, revision \\code{{{provenance['extractbench']['revision'][:7]}}}. Full CSV with all metrics: \\code{{docs/results/extractbench-leaderboard.csv}}.}}\n")
        out.append(r"\end{landscape}" + "\n")
    (HERE.parent / "results-tables.tex").write_text("".join(out))
    print("Rendered 15 UNIKIE systems + 3 local variants; 49 ExtractBench systems + 2 local variants.")


if __name__ == "__main__":
    main()
